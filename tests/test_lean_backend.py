"""tests/test_lean_backend.py — Lean backend end-to-end validation.

Ring 1 Day 2: synthesize → translate → drop into lean/ → lake build.
Success = the generated theorem compiles.  A regression here means
either the translator produced something Lean can't parse, or the
chosen tactic can't discharge the obligation.

The test runs in a self-contained way:
  1. Synthesize the benchmark.
  2. Translate the chosen ranking-LB into Lean.
  3. Write to `lean/SynthLean/Generated.lean`.
  4. Shell out to `lake build`.

Skip cleanly if `lake` isn't on PATH (CI installs it via
`leanprover/lean-action@v1`; locally, run `./lean/setup.sh`).
"""
from __future__ import annotations
import importlib.util
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

_LAKE = shutil.which("lake") or os.path.expanduser("~/.elan/bin/lake")
_HAS_LAKE = os.path.exists(_LAKE) and os.access(_LAKE, os.X_OK)


def _load_problem(rel_path: str):
    spec = importlib.util.spec_from_file_location("_bench", REPO / rel_path)
    mod = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(mod)
    return mod.PROBLEM


def _build_generated(theorems: dict[str, str]) -> None:
    """Write the theorems to a TEMPFILE (NOT the committed
    `Generated.lean`) and run `lake env lean <file>`.  Each key is a
    theorem name (informational); each value is the full Lean text
    emitted by translate.

    Using a tempfile + `lake env lean` instead of writing to a
    checked-in file and running `lake build` avoids polluting
    `git status` on every test run (Day 9 issue) and avoids race
    conditions if tests run in parallel.
    """
    import os, tempfile
    src = [
        "-- Generated by tests/test_lean_backend.py — tempfile.",
        "import SynthLean.Basic     -- for `store`",
        "open SynthLean",
        "namespace SynthLean.VerifyTmp",
        "",
    ]
    src.extend(theorems.values())
    src.append("end SynthLean.VerifyTmp")
    text = "\n".join(src) + "\n"

    with tempfile.NamedTemporaryFile(
        mode="w", suffix=".lean", delete=False, encoding="utf-8"
    ) as f:
        f.write(text)
        tmp_path = f.name
    try:
        r = subprocess.run(
            [_LAKE, "env", "lean", tmp_path],
            cwd=REPO / "lean",
            capture_output=True, text=True, timeout=180,
        )
    finally:
        try:
            os.unlink(tmp_path)
        except OSError:
            pass

    assert r.returncode == 0, (
        f"lake env lean failed\n"
        f"stdout:\n{r.stdout}\n"
        f"stderr:\n{r.stderr}\n"
        f"source (first 1500 chars):\n{text[:1500]}"
    )


