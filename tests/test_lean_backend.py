def test_grid_paths_inductive_emits() -> None:
    """Day 6 — translator emits the grid_paths inner-inductive theorem
    (axiom declarations + theorem text).  Compiles axioms cleanly;
    the theorem proof currently fails on one conjunct (column-0-
    preservation, needs the case-on-Update tactic pattern from
    Day 5's hand-written proof in SynthLean.GridPaths).  Day 7
    work: extend the generic tactic chain to handle this class.

    For now this test only checks the EMISSION (no `lake build`).
    The hand-written proof in `lean/SynthLean/GridPaths.lean`
    demonstrates the obligation IS provable in Lean — the gap is
    in the auto-generated tactic chain, not Lean's capability.
    """
    from synth.lean_backend import (
        theorem_for_safety_inductive, emit_axiom_declarations,
    )
    from synth.result import Solution
    from synth.expand import expand

    problem = _load_problem("benchmarks/grid_paths.py")
    expand(problem)
    syn_atoms = {}
    for hole_id, candidates in problem.atoms.items():
        if hole_id.startswith("tau@"):
            syn_atoms[hole_id] = list(candidates)
        else:
            syn_atoms[hole_id] = candidates[0]
    sol = Solution(choices={}, atoms=syn_atoms)

    axioms = emit_axiom_declarations(problem)
    theorem = theorem_for_safety_inductive(
        problem, sol, "L1",
        theorem_name="grid_paths_inner_inductive"
    )

    # Text-level checks: the right axioms, hypotheses, and conclusion
    # shape made it into the generated source.
    assert "axiom paths : Int → Int → Int" in axioms
    assert "user_axiom_0" in axioms
    assert "user_axiom_1" in axioms
    assert "user_axiom_2" in axioms
    assert "(L : Int → Int → Int)" in theorem
    assert "(L' : Int → Int → Int)" in theorem
    assert "store2d" in theorem
    # 9 τ atoms → 9 named hypotheses.
    for k in range(9):
        assert f"h_tau_{k}" in theorem, f"missing h_tau_{k}"
    # paths reference in conclusion (the quantified post-state atoms).
    assert "paths" in theorem


def test_merge_l1_entry_chain_emits() -> None:
    """#167.2 — chain-aware entry-bundle emits a structurally
    correct theorem for merge_two_sorted's L1 (chained loops).

    Asserts:
      - Per-state binders for vars (s0, s1, s2).
      - Chain item hyps: SB(B0)'s trans + Loop(L0)'s abstract
        transition (τ + ¬g + frame eqs).
      - Goal: τ@L1 atoms at state-2 names.
    """
    from synth.lean_backend.translate import (
        theorem_for_entry_bundle_chain,
    )
    from synth.result import Solution
    from synth.expand import expand

    problem = _load_problem("benchmarks/stretch/merge_two_sorted.py")
    expand(problem)
    sol_atoms = {}
    for hid, cands in problem.atoms.items():
        if hid.startswith("tau@"):
            sol_atoms[hid] = list(cands)
        else:
            sol_atoms[hid] = cands[0]
    sol = Solution(choices={}, atoms=sol_atoms)

    theorem = theorem_for_entry_bundle_chain(
        problem, sol, "L1", theorem_name="merge_L1_entry"
    )

    # Per-state binders.
    for s in ("s0", "s1", "s2"):
        assert f"i_{s}" in theorem, f"missing i_{s} binder"
        assert f"j_{s}" in theorem, f"missing j_{s} binder"
        assert f"C_{s}" in theorem, f"missing C_{s} binder"
    # B0 init transitions at state 0 → state 1.
    assert "h_i0_trans_i" in theorem
    assert "h_i0_trans_j" in theorem
    # L0 abstract transition: τ@L0 atoms at state 2.
    assert "h_i1_L0_tau_0" in theorem
    assert "h_i1_L0_not_g" in theorem
    # Frame eqs for vars NOT modified by L0's body.
    assert "h_i1_L0_frame_n" in theorem
    # Goal references state-2 vars.
    assert "is_sorted C_s2 (i_s2 + j_s2)" in theorem


