def test_merge_final_post_chain_emits() -> None:
    """#167.3 — chain-aware chain-bundle emits a theorem for
    merge_two_sorted's sc15 (final bundle-post).  Chain walks
    [SB(B0), Loop(L0), Loop(L1), Loop(L2)] — 5 states.  Goal is
    Fpost (`is_sorted C_s4 (n_s4 + p_s4) == 1`).
    """
    from synth.lean_backend.translate import (
        theorem_for_chain_bundle_chain,
    )
    from synth.result import Solution
    from synth.expand import expand

    problem = _load_problem("benchmarks/stretch/merge_two_sorted.py")
    expand(problem)
    sol_atoms = {}
    for hid, cands in problem.atoms.items():
        if hid.startswith("tau@"):
            sol_atoms[hid] = list(cands)
        else:
            sol_atoms[hid] = cands[0]
    sol = Solution(choices={}, atoms=sol_atoms)

    theorem = theorem_for_chain_bundle_chain(
        problem, sol, "L0", theorem_name="merge_final_post"
    )

    # 5 states (state 0 .. state 4) — every var has 5 binders.
    for s in range(5):
        assert f"C_s{s}" in theorem, f"missing C_s{s} binder"
    # Every Loop in the chain contributes an abstract transition.
    for lid in ("L0", "L1", "L2"):
        assert f"{lid}_tau_0" in theorem, f"missing {lid} τ hyps"
        assert f"{lid}_not_g" in theorem, f"missing {lid} ¬g hyp"
    # Goal: Fpost at state-4.
    assert "is_sorted C_s4" in theorem


